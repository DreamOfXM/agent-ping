#!/usr/bin/env python
"""把灯舱那几枚剪影烘成 src/edge_marks.h（每像素一字节＝形状覆盖度，RGB 由上传时涂）。

输入不是仓库里的东西：三枚剪影来自 2026-11-01 定稿那轮的遮罩 PNG（官方 .icns 抠形），
Claude 那枚直接取 src/agent_icons.h 里已内嵌位图的 alpha（它本来就是透明底上的星芒）。
所以这个脚本只在重新生成时跑得通，克隆仓库的人拿到的是产物本身。
"""
import math
import pathlib
import re

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
MASKS = {
    "Qoder": ROOT / "evidence/2026-11-01-edge-dock2/src_icons/m_qoder_bold.png",
    "WorkBuddy": ROOT / "evidence/2026-11-01-edge-dock2/src_icons/m_workbuddy.png",
    "ZCode": ROOT / "evidence/2026-11-01-edge-dock2/src_icons/m_zcode.png",
}
N = 96
OUT = ROOT / "src/edge_marks.h"


def alpha_bytes(img):
    a = img.convert("RGBA").getchannel("A")
    if a.size != (N, N):
        a = a.resize((N, N), Image.LANCZOS)
    return a.tobytes()


def claude_alpha():
    src = (ROOT / "src/agent_icons.h").read_text()
    m = re.search(r'static const char\* kAgentHexClaude =\s*((?:"[0-9a-fA-F]*"\s*)+);', src)
    body = "".join(re.findall(r'"([0-9a-fA-F]*)"', m.group(1)) if m else [])
    nb = len(body) // 2
    n = int(math.isqrt(nb // 4))
    return Image.frombytes("RGBA", (n, n), bytes.fromhex(body))


def emit(name, data, note):
    hexs = data.hex().upper()
    lines = [f'// {note}'] if note else []
    lines.append(f"static const char* kMarkHex{name} =")
    for i in range(0, len(hexs), 96):
        lines.append('    "' + hexs[i:i + 96] + '"')
    lines[-1] += ";"
    return "\n".join(lines) + "\n"


parts = [
    "/* Generated by Tools/make_edge_marks.py — 右缘灯舱那三枚（+Claude）剪影。\n"
    f"   每枚 {N}x{N}，一像素一字节（形状覆盖度），上传时涂成白底＋这道 alpha，\n"
    "   画的时候用条子自己的墨色染色（稿子的 mask + background-color:currentColor）。\n"
    "   本工程没有 PNG 解码器，所以位图以裸十六进制存着，与 brand_icon.h 同一套路。 */\n"
    f"static const int kMarkN = {N};\n",
]
for name, path in MASKS.items():
    parts.append(emit(name, alpha_bytes(Image.open(path)), f"取自 {path.relative_to(ROOT)} 的 alpha"))
parts.append(emit("Claude", alpha_bytes(claude_alpha()),
                  "取自 src/agent_icons.h 内嵌 Claude 位图的 alpha（本来就是透明底星芒）"))

OUT.write_text("\n".join(parts))
print(OUT, OUT.stat().st_size, "bytes,", N, "x", N, "x", len(parts) - 1, "marks")
